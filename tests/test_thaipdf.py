class TestDoesNotDamageNormalText:
    """กลุ่มควบคุม — ข้อความที่ถูกต้องอยู่แล้วต้องออกมาเหมือนเดิมเป๊ะ"""

    @pytest.mark.parametrize(
        "text",
        [
            "ผู้เยาว์เดินผ่านเต๋าแห่งหนึ่ง",     # ไทยปกติที่ถูกต้องแล้ว
            "Xian Ni chapter 1201",              # อังกฤษ
            "ตอนที่ 1201",                        # ไทยปนตัวเลข
            "",                                   # ว่าง
            "ก" * 100,                            # ไม่มีมาร์กเลย
        ],
    )
    def test_text_without_pua_is_untouched(self, text):
        assert fix_thai_pua(text) == text

    def test_detector_says_no_for_clean_text(self):
        assert has_thai_pua("ผู้เยาว์เดินผ่าน") is False

    def test_detector_says_yes_for_dirty_text(self):
        assert has_thai_pua("ผูเยาว") is True


class TestMapCoversWhatTheFileActuallyContains:
    """14 codepoint ที่นับได้จากไฟล์จริง — ขาดตัวไหนคือวรรณยุกต์หายไปทั้งเล่ม"""

    FOUND_IN_FILE = [
        0xF701, 0xF702, 0xF703, 0xF704, 0xF705, 0xF706, 0xF708,
        0xF70A, 0xF70B, 0xF70D, 0xF70E, 0xF710, 0xF712, 0xF713, 0xF714,
    ]

    @pytest.mark.parametrize("cp", FOUND_IN_FILE)
    def test_every_observed_codepoint_is_mapped(self, cp):
        assert chr(cp) in PUA_MAP, f"U+{cp:04X} มีอยู่ในไฟล์จริงแต่ไม่มีในตาราง"

    def test_every_mapping_target_is_a_real_thai_character(self):
        """กันพิมพ์ผิดในตาราง — ปลายทางต้องอยู่ในบล็อกภาษาไทยของ Unicode"""
        for src, dst in PUA_MAP.items():
            assert dst, f"{src!r} แมปไปค่าว่าง"
            for ch in dst:
                assert 0x0E00 <= ord(ch) <= 0x0E7F, (
                    f"U+{ord(src):04X} → U+{ord(ch):04X} ไม่ใช่อักษรไทย"
                )
