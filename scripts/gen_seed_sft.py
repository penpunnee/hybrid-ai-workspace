def main(out_path: str = "data/finetune_seed.jsonl"):
    kwan = ASSISTANTS["🧡 ขวัญ (Logic)"]
    system = kwan["system_prompt"]

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    n = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for user, assistant in SEED:
            ex = {"messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
                {"role": "assistant", "content": assistant},
            ]}
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")
            n += 1
    print(f"✅ seed → {out_path} ({n} ตัวอย่าง)")
    if n < 50:
        print(f"💡 มี {n} ตัวอย่าง — bootstrap ได้ แต่แนะนำผสมกับ 👍 จริงให้ถึง 50-200+ "
              f"(ดู docstring: รวม seed + export ก่อนเทรน)")
    return n


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/finetune_seed.jsonl")
