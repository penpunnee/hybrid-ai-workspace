# ── ตารางแมป ───────────────────────────────────────────────────────────────────
# ชุดที่ 1 — สระบน (ยืนยันครบทั้ง 4 ตัวจากไฟล์จริง)
#   F701 ิ  ← 'เปดใช'      = เปิดใช้
#   F702 ี  ← 'ปกเพลิง'    = ปีกเพลิง
#   F703 ึ  ← 'ฝกฝน'       = ฝึกฝน
#   F704 ื  ← 'ฝนลิขิตฟ'   = ฝืนลิขิตฟ้า (ชื่อเรื่อง)
#
# ชุดที่ 2/3 — วรรณยุกต์ + ทัณฑฆาต ซ้ำกันสองชั้นความสูง (F705.. และ F70A..)
#   F705 ่  ← 'ฝามือ'      = ฝ่ามือ
#   F706 ้  ← 'ทองฟา'      = ท้องฟ้า
#   F708 ๋  ← 'กระเปา'     = กระเป๋า
#   F70A ่  ← 'ผาน'        = ผ่าน           (พบบ่อยสุด 3,381 ครั้ง)
#   F70B ้  ← 'ผูเยาว'     = ผู้เยาว์        (3,186 ครั้ง)
#   F70D ๋  ← 'เตา'        = เต๋า
#   F70E ์  ← 'องครักษ'    = องครักษ์
#   F707/F709/F70C = ๊/์/๊ เติมตามตำแหน่งในชุด — **ไม่พบในไฟล์ตัวอย่าง 0 ครั้ง**
#
# ชุดที่ 4 — ใช้เมื่อมีสระบนซ้อนอยู่แล้ว จึงต้องยกมาร์กสูงขึ้นอีกชั้น
#   F710 ั  ← 'ปลูกฝง'                = ปลูกฝัง
#   F712 ็  ← 'เปน'                   = เป็น
#   F713 ่  ← 'เปอย' = เปื่อย · 'ปน' = ปั่น
#   F714 ้  ← 'กำปน'            = กำปั้น
#   F715–F717 = ๊/๋/์ เติมตามตำแหน่ง — **ไม่พบในไฟล์ตัวอย่าง**
PUA_MAP: dict[str, str] = {
    # สระบน
    "": "ิ",  # ิ
    "": "ี",  # ี
    "": "ึ",  # ึ
    "": "ื",  # ื
    # วรรณยุกต์ ชั้นที่ 1
    "": "่",  # ่
    "": "้",  # ้
    "": "๊",  # ๊   (เติมตามตำแหน่ง)
    "": "๋",  # ๋
    "": "์",  # ์   (เติมตามตำแหน่ง)
    # วรรณยุกต์ ชั้นที่ 2
    "": "่",  # ่
    "": "้",  # ้
    "": "๊",  # ๊   (เติมตามตำแหน่ง)
    "": "๋",  # ๋
    "": "์",  # ์
    # สระ/วรรณยุกต์ ชั้นยกสูง
    "": "ั",  # ั
    "": "ํ",  # ํ   (เติมตามตำแหน่ง)
    "": "็",  # ็
    "": "่",  # ่
    "": "้",  # ้
    "": "๊",  # ๊   (เติมตามตำแหน่ง)
    "": "๋",  # ๋   (เติมตามตำแหน่ง)
    "": "์",  # ์   (เติมตามตำแหน่ง)
    # ── พยัญชนะที่ถูกตัดหางทิ้ง ──────────────────────────────────────────
    # 🔴 PUA ไม่ได้มีแค่มาร์ก! ญ กับ ฬ มีหางห้อยลงข้างล่าง พอมีสระอยู่ใต้/บน
    # ฟอนต์จะสลับไปใช้ตัวที่ตัดหางทิ้งซึ่งอยู่ในโซน PUA
    #   F70F ญ ← 'อกตัญู'  = อกตัญญู
    #   F71D ฬ ← 'นาิกา'   = นาฬิกา
    # เจอเพราะไล่ตัวที่เหลือค้างหลังแปลงทั้งเล่ม (20 จาก 305,911 = 0.007%)
    "": "ญ",  # ญ
    "": "ฬ",  # ฬ
}

_TABLE = str.maketrans(PUA_MAP)

# ช่วง PUA ของ BMP — ใช้ตรวจแบบ "ช่วง" ไม่ใช่รายตัว เพื่อให้ codepoint ที่เรายัง
# ไม่เคยเห็นไม่หลุดออกไปเงียบๆ
_PUA_LO, _PUA_HI = 0xE000, 0xF8FF


def fix_thai_pua(text: str) -> str:
    """แทนที่ PUA ด้วยสระ/วรรณยุกต์ไทยมาตรฐาน

    ข้อความที่ไม่มี PUA จะถูกคืนกลับไปเหมือนเดิมทุกตัวอักษร (ไม่มี normalize
    ไม่มีจัดลำดับมาร์กใหม่) — ตัวนี้ทำหน้าที่เดียวคือถอดรหัสฟอนต์
    """
    if not text:
        return text
    return text.translate(_TABLE)


def has_thai_pua(text: str) -> bool:
    """ยังเหลือตัวอักษรโซน PUA อยู่ไหม — ใช้เป็นด่านหลังแปลง

    เหลือแม้ตัวเดียวคือตัวที่ TTS จะอ่านไม่ออก (หรืออ่านเป็นเสียงประหลาด)
    """
    return any(_PUA_LO <= ord(ch) <= _PUA_HI for ch in text)
