_TABLE = str.maketrans(PUA_MAP)

# ช่วง PUA ของ BMP — ใช้ตรวจแบบ "ช่วง" ไม่ใช่รายตัว เพื่อให้ codepoint ที่เรายัง
# ไม่เคยเห็นไม่หลุดออกไปเงียบๆ
_PUA_LO, _PUA_HI = 0xE000, 0xF8FF


def fix_thai_pua(text: str) -> str:
    """แทนที่ PUA ด้วยสระ/วรรณยุกต์ไทยมาตรฐาน

    ข้อความที่ไม่มี PUA จะถูกคืนกลับไปเหมือนเดิมทุกตัวอักษร (ไม่มี normalize
    ไม่มีจัดลำดับมาร์กใหม่) — ตัวนี้ทำหน้าที่เดียวคือถอดรหัสฟอนต์
    """
    if not text:
        return text
    return text.translate(_TABLE)


def fix_inserted_spaces(text: str) -> str:
    """ซ่อมช่องว่างแทรกจาก PDF — สูตร ③ "เต็มสูตร" ที่ user เลือกด้วยหู

    โรคคนละตัวกับ PUA — เจอจาก `Perfect World โลกอันสมบูรณ์แบบ (จบ).pdf` (21.2M ตัวอักษร):
    ฟอนต์/เลย์เอาต์ทำให้ `pypdf` คายช่องว่างปลอมแทรกกลางคำทั้งเล่ม
    (ก่อนมาร์ก 200,045 · หลังมาร์ก 377,533 · แยกทีละตัวอักษร 26,293 ช่วง)
    ไม่ซ่อม = TTS หยุดหายใจกลางคำตลอด 363 ชั่วโมง

    🔑 **ลำดับ 5 ขั้นนี้ห้ามสลับ** — ไม่ได้ออกแบบจากทฤษฎี แต่สอบกลับจากไฟล์เสียง
    v_3 "เต็มสูตร" ที่ user ฟังเทียบหลายสูตรแล้วเคาะ (2026-08-11) · brute-force
    ลำดับ operation จนตรงไฟล์นั้น 860/860 ตัวอักษร (2026-08-12 — เทสตรึงไว้ด้วย
    fixture `pw_golden_v3.txt`):

      B  ยุบช่วง "ตัวอักษรไทยเดี่ยวคั่นวรรค" ≥6 ตัวติดกัน (ทำก่อน \\n→วรรค
         โดยตั้งใจ — ช่วงที่คร่อมบรรทัดจะไม่ถูกยุบข้ามบรรทัด)
      N  \\n → วรรค (บรรทัดของ PDF ไม่ใช่โครงสร้างประโยค)
      AM ํ + า → ำ (ฟอนต์แยกสระอำเป็นสองตัว)
      A1 ลบวรรคก่อนมาร์ก ('เผ่าพันธุ ์' → 'เผ่าพันธุ์')
      A2 ลบวรรคหลังมาร์ก ('เป็ น' → 'เป็น') — กลืนวรรคจริงหลังคำที่ลงท้าย
         ด้วยมาร์กไปด้วย ('ใหญ่ อสูร'→'ใหญ่อสูร') แต่ผลฟังจริงแล้วดีสุด
         เพราะ TTS ไทยตัดคำเองได้ ส่วนวรรคปลอมกลางคำมันช่วยตัวเองไม่ได้

    ใช้ตอน **ขาเข้าเท่านั้น** (เหตุผลเดียวกับ `fix_thai_pua` ใน routers/reader.py:
    ความยาวข้อความเปลี่ยน ที่คั่นหน้าเก่าจะเลื่อน) และหลัง `fix_thai_pua` เสมอ
    เพราะมาร์กที่ยังอยู่ในโซน PUA จะมองไม่เห็นใน A1/A2
    """
    if not text:
        return text
    text = _RE_SPLIT_RUN.sub(lambda m: m.group().replace(" ", ""), text)
    text = text.replace("\n", " ")
    text = _fix_sara_am(text)
    text = _RE_SPACE_BEFORE_MARK.sub(r"\1", text)
    text = _RE_SPACE_AFTER_MARK.sub(r"\1", text)
    # ── pass เก็บตก (วัดจากทั้งเล่มจริง 2026-08-12) ──
    # B รอบสอง: ช่วงแยกตัวอักษรที่คร่อมบรรทัดมองเห็นได้หลัง \n→วรรคเท่านั้น (เหลือ 190 ช่วง)
    # AM รอบสอง: A2 เพิ่งดึง ํ กับ า มาชิดกันหลัง AM รอบแรกผ่านไปแล้ว (เหลือ 86 จุด)
    # ทั้งคู่เป็นโรคแน่นอน ไม่มีทางเป็นวรรคจริง — และไม่กระทบ golden (เทสตรึงยืนยัน)
    text = _RE_SPLIT_RUN.sub(lambda m: m.group().replace(" ", ""), text)
    text = _fix_sara_am(text)
    return text


def _fix_sara_am(text: str) -> str:
    """รวมสระอำที่ฟอนต์แยกส่วน — ทั้งแบบชิด (ํา→ำ) และแบบมีวรรณยุกต์คั่น

    'คํ่าคืน' (ค+ํ+่+า) → 'ค่ำคืน' (ค+่+ำ) — เจอจากประโยคเปิดเรื่อง PW ตัวจริง
    หลัง import 2026-08-12 · วัดทั้งเล่ม 20,069 จุด (รวม 'นํ้า' ที่โผล่ทุกหน้า)
    ไม่กำกวม: ํ+วรรณยุกต์+า ไม่มีการอ่านแบบอื่นในภาษาไทย · xianni มี 0 จุด
    """
    text = text.replace("ํา", "ำ")
    return _RE_AM_TONE.sub(r"\1ำ", text)


# มาร์ก = ตัวที่ต้องเกาะพยัญชนะ: ั ิ ี ึ ื ุ ู ฺ ็ ่ ้ ๊ ๋ ์ ํ ๎ — วรรคขนาบมัน
# คือวรรคปลอมแน่นอน (ภาษาไทยไม่มีมาร์กลอยเดี่ยวๆ กลางประโยค)
_MARK_CLASS = r"[ัิ-ฺ็-๎]"
_THAI_CLASS = r"[฀-๿]"

_RE_SPLIT_RUN = _re.compile(rf"(?:{_THAI_CLASS} ){{5,}}{_THAI_CLASS}")
_RE_SPACE_BEFORE_MARK = _re.compile(rf"\s+({_MARK_CLASS})")
_RE_SPACE_AFTER_MARK = _re.compile(rf"({_MARK_CLASS})\s+")
_RE_AM_TONE = _re.compile(r"ํ([่-๋])า")  # ํ + วรรณยุกต์ + า → วรรณยุกต์ + ำ


# อัตรา "ช่องว่างก่อนมาร์ก" ต่อตัวอักษร — วัดจริงสองฝั่ง (2026-08-12):
# Perfect World 0.94% · เล่มสะอาด (xianni ใน prod) 0.0000% ⇒ 0.1% อยู่กลางทุ่งโล่ง
_SPACING_DISEASE_THRESHOLD = 0.001
_RE_A1_DETECT = _re.compile(rf"\S\s+{_MARK_CLASS}")
# ตรวจจากหัวเล่มพอ — โรคนี้มาจากฟอนต์/เลย์เอาต์ จึงกระจายทั้งเล่ม ไม่ต้องสแกน 21M
_DETECT_SAMPLE_CHARS = 200_000


def has_inserted_spaces(text: str) -> bool:
    """เล่มนี้เป็นโรคช่องว่างแทรกไหม — ใช้ตัดสินก่อนเรียก `fix_inserted_spaces`

    ทำไมต้องมีด่านนี้: ขั้น A2 ของสูตรกลืนวรรคจริงหลังคำที่ลงท้ายด้วยมาร์ก
    ("อากาศดี ฉัน"→"อากาศดีฉัน") — คุ้มเฉพาะเล่มที่มีวรรคปลอมกลางคำทั้งเล่ม
    เล่มสะอาดห้ามโดน
    """
    if not text:
        return False
    sample = text[:_DETECT_SAMPLE_CHARS]
    return len(_RE_A1_DETECT.findall(sample)) / len(sample) > _SPACING_DISEASE_THRESHOLD


def has_thai_pua(text: str) -> bool:
    """ยังเหลือตัวอักษรโซน PUA อยู่ไหม — ใช้เป็นด่านหลังแปลง

    เหลือแม้ตัวเดียวคือตัวที่ TTS จะอ่านไม่ออก (หรืออ่านเป็นเสียงประหลาด)
    """
    return any(_PUA_LO <= ord(ch) <= _PUA_HI for ch in text)
